// Generates @cgw/api's types from the server's checked-in OpenAPI document, which the server's
// build writes (server/openapi/v1.json). With --check it fails when the checked-in types differ:
// a change to the API shows in review and cannot drift from the client.
//   node scripts/api-generate.mjs           write packages/api/src/schema.ts
//   node scripts/api-generate.mjs --check   fail if it is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { root } from './lib.mjs';

const require = createRequire(join(root, 'packages', 'api', 'package.json'));
const generator = await import(pathToFileURL(require.resolve('openapi-typescript')).href);
const openapiTS = generator.default?.default ?? generator.default ?? generator.openapiTS;
const astToString = generator.astToString ?? generator.default?.astToString;
const prettierModule = await import(
  pathToFileURL(createRequire(join(root, 'package.json')).resolve('prettier')).href
);
const prettier = prettierModule.default ?? prettierModule;

const source = join(root, 'server', 'openapi', 'v1.json');
const target = join(root, 'packages', 'api', 'src', 'schema.ts');
const ast = await openapiTS(new URL(pathToFileURL(source).href), { alphabetize: true });
const header =
  '// Generated by scripts/api-generate.mjs from server/openapi/v1.json. Do not edit: change the\n' +
  "// server's endpoints, build it, and run `pnpm api:generate`.\n";
const options = (await prettier.resolveConfig(target)) ?? {};
const text = await prettier.format(header + astToString(ast), { ...options, filepath: target });

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('packages/api/src/schema.ts is stale: run `pnpm api:generate` and commit it.');
    process.exit(1);
  }
  console.log('The API client matches the OpenAPI document.');
} else {
  writeFileSync(target, text);
  console.log('Wrote packages/api/src/schema.ts.');
}
