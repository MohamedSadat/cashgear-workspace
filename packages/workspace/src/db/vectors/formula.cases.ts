// db-formula-vectors.json: the formula language. `evaluate` suites: each expression evaluated on
// the suite's row as one more formula property of its database (`evaluateFormula`), with the
// hand-written result and static kind (null when the formula has an error). `toNames` / `toIds`
// suites: the editor's rewriting.
