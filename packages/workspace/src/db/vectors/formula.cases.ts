export interface FormulaCase {
  expression: string;
  expected: { value: CellValue; type: StaticType | null } | string;
}

export interface FormulaSuite {
  kind: 'evaluate' | 'toNames' | 'toIds';
  name: string;
  database: VectorDatabase;
  row?: VectorRow;
  cases: FormulaCase[];
}

const f = (id: string, expression: string, trashedAt?: string) =>
  prop(id, 'formula', { formula: { expression }, ...(trashedAt ? { trashedAt } : {}) }, id);

